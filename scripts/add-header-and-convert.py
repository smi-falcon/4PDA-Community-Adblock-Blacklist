import sys
from datetime import datetime, timezone

SOURCE = "Blacklist_hosts.txt"

MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]

FORMATS = {
    "FQDN": {"file": "Blacklist_fqdn.txt", "comment": "#", "title": "fqdn", "desc": "domain"},
    "Reduced FQDN": {"file": "Blacklist_reduced_fqdn.txt", "comment": "#", "title": "reduced fqdn", "desc": "domain (subdomains pruned)"},
    "DualServer": {"file": "Blacklist_dualserver.txt", "comment": ";", "title": "dualserver", "desc": "domain=0.0.0.0"},
    "DNSmasq": {"file": "Blacklist_dnsmasq.txt", "comment": "#", "title": "dnsmasq", "desc": "address=/domain/ (subdomains pruned)"},
    "Unbound": {"file": "Blacklist_unbound.txt", "comment": "#", "title": "unbound", "desc": "local-zone: \"domain\" always_nxdomain (subdomains pruned)"},
    "Privoxy": {"file": "Blacklist_privoxy.txt", "comment": "#", "title": "privoxy", "desc": "domain, *.domain (subdomains pruned)"},
    "RPZ": {"file": "Blacklist_rpz.txt", "comment": ";", "title": "rpz", "desc": "domain CNAME ., *.domain CNAME . (subdomains pruned)"},
    "IPv6": {"file": "Blacklist_ipv6.txt", "comment": "#", "title": "ipv6", "desc": "0.0.0.0 domain, :: domain"},
    "Compressed": {"file": "Blacklist_compressed.txt", "comment": "#", "title": "compressed", "desc": "0.0.0.0 d1 d2 ... d9"},
    "IPv6 Compressed": {"file": "Blacklist_ipv6_compressed.txt", "comment": "#", "title": "ipv6 compressed", "desc": "0.0.0.0 d1 ... d9, :: d1 ... d9"},
}


def read_domains(path):
    domains = []
    seen = set()
    with open(path, "r", encoding="utf-8-sig", errors="replace") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            if parts[0] != "0.0.0.0":
                continue
            domain = parts[1].lower()
            if not domain or domain == "0.0.0.0":
                continue
            if domain in seen:
                continue
            seen.add(domain)
            domains.append(domain)
    return domains


def prune_subdomains(domains):
    domain_set = set(domains)
    result = []
    for domain in domains:
        parts = domain.split(".")
        has_parent = False
        for i in range(1, len(parts)):
            parent = ".".join(parts[i:])
            if parent in domain_set:
                has_parent = True
                break
        if not has_parent:
            result.append(domain)
    return result


def build_header(name, records, comment, desc):
    now = datetime.now(timezone.utc)
    last_modified = f"{now.day:02d} {MONTHS[now.month - 1]} {now.year} {now.hour:02d}:{now.minute:02d} UTC"
    title = FORMATS[name]["title"]
    c = comment
    lines = [
        f"{c} Title: 4PDA Community {title} blacklist",
        f"{c} Last modified: {last_modified}",
        f"{c} Expires: 1 day",
        f"{c} Author: Schakal",
        f"{c} Homepage: https://schakal.hopto.org/",
        f"{c} Source: https://schakal.hopto.org/hosts.txt",
        f"{c} Records: {records}",
        "",
        f"{c} Converted from hosts format to {name}",
        f"{c} Original format: hosts (0.0.0.0 domain)",
        f"{c} Conversion: {desc}",
        f"{c} Generated by: Hosts-Conversions (Python port)",
        "",
    ]
    return "\n".join(lines)


def write_output(name, body, records):
    meta = FORMATS[name]
    with open(meta["file"], "w", encoding="utf-8", newline="\n") as f:
        f.write(build_header(name, records, meta["comment"], meta["desc"]) + "\n")
        f.write("\n".join(body) + "\n")


def to_fqdn(domains):
    return list(domains)


def to_reduced_fqdn(domains):
    return prune_subdomains(domains)


def to_dualserver(domains):
    return [f"{d}=0.0.0.0" for d in domains]


def to_dnsmasq(domains):
    return [f"address=/{d}/" for d in prune_subdomains(domains)]


def to_unbound(domains):
    return [f'local-zone: "{d}" always_nxdomain' for d in prune_subdomains(domains)]


def to_privoxy(domains):
    result = []
    for d in prune_subdomains(domains):
        result.append(d)
        result.append(f"*.{d}")
    return result


def to_rpz(domains):
    result = []
    for d in prune_subdomains(domains):
        result.append(f"{d} CNAME .")
        result.append(f"*.{d} CNAME .")
    return result


def to_ipv6(domains):
    result = []
    for d in domains:
        result.append(f"0.0.0.0 {d}")
        result.append(f":: {d}")
    return result


def to_compressed(domains, chunk=9):
    result = []
    for i in range(0, len(domains), chunk):
        result.append("0.0.0.0 " + " ".join(domains[i:i + chunk]))
    return result


def to_ipv6_compressed(domains, chunk=9):
    result = []
    for i in range(0, len(domains), chunk):
        batch = " ".join(domains[i:i + chunk])
        result.append(f"0.0.0.0 {batch}")
        result.append(f":: {batch}")
    return result


def main():
    domains = read_domains(SOURCE)
    if not domains:
        sys.exit(1)
    pruned = prune_subdomains(domains)
    write_output("FQDN", to_fqdn(domains), len(domains))
    write_output("Reduced FQDN", to_reduced_fqdn(domains), len(pruned))
    write_output("DualServer", to_dualserver(domains), len(domains))
    write_output("DNSmasq", to_dnsmasq(domains), len(pruned))
    write_output("Unbound", to_unbound(domains), len(pruned))
    write_output("Privoxy", to_privoxy(domains), len(pruned))
    write_output("RPZ", to_rpz(domains), len(pruned))
    write_output("IPv6", to_ipv6(domains), len(domains))
    write_output("Compressed", to_compressed(domains), len(domains))
    write_output("IPv6 Compressed", to_ipv6_compressed(domains), len(domains))


if __name__ == "__main__":
    main()