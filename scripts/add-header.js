const fs = require('fs');

const adblockFile = 'Blacklist_adblock.txt';

const rules = fs.readFileSync(adblockFile, 'utf8').trim().split('\n');
const records = rules.length;

const now = new Date();
const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const day = String(now.getUTCDate()).padStart(2, '0');
const month = months[now.getUTCMonth()];
const year = now.getUTCFullYear();
const hours = String(now.getUTCHours()).padStart(2, '0');
const minutes = String(now.getUTCMinutes()).padStart(2, '0');
const lastModified = `${day} ${month} ${year} ${hours}:${minutes} UTC`;

const header = [
  '! Title: 4PDA Community adblock blacklist',
  `! Last modified: ${lastModified}`,
  '! Expires: 1 day',
  '! Author: Schakal',
  '! Homepage: https://schakal.ru/',
  '! Source: https://schakal.ru/hosts/hosts.txt',
  `! Records: ${records}`,
  '',
  '! Converted from hosts format to AdBlock/AdGuard syntax',
  '! Original format: hosts (0.0.0.0 domain)',
  '! Conversion: domain → ||domain^',
  '! Generated by: @adguard/hostlist-compiler v2.1.1',
  ''
].join('\n');

fs.writeFileSync(adblockFile, header + '\n' + rules.join('\n') + '\n');